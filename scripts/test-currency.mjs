import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {completeCurrencyRates,preferredCurrency,convertFromUsd,convertFromAud,fallbackCurrencyRates} from "../coffee/lib/currency.js";
import {formatCurrency} from "../coffee/lib/money.js";
assert.equal(preferredCurrency("?currency=GBP","EUR"),"GBP");
assert.equal(preferredCurrency("?currency=gbp","USD"),"GBP");
assert.equal(preferredCurrency("?currency=invalid","EUR"),"EUR");
assert.equal(preferredCurrency("","bad"),"USD");
const legacy={AUD:1,USD:0.6939,EUR:0.60702};
assert.equal(completeCurrencyRates(legacy).GBP,0.5226);
assert.equal(completeCurrencyRates({GBP:NaN,USD:0}).USD,0.6939);
assert.equal(convertFromAud(10,"GBP",legacy),5.23);
assert.equal(convertFromUsd(2.75,"GBP",legacy),2.07);
assert.equal(convertFromUsd(2.75,"USD",fallbackCurrencyRates),2.75);
assert.equal(formatCurrency(2.07,"GBP"),"£2.07");
const provider=readFileSync(new URL("../coffee/components/currency-provider.js",import.meta.url),"utf8");
assert.ok(!provider.includes("fetch("),"Currency switching must not add network requests");
assert.ok(provider.includes("12*60*60*1000"));
console.log("PASS: GBP AUD-base conversion, legacy cache completion, share URL priority, £ formatting, 12h cache, zero exchange-rate requests.");
